#!/usr/bin/env bash
# Writes THIRD_PARTY_LICENSES: the license text of every module that a hookinlet release
# binary is built from, and of the Go toolchain's own library that every Go binary
# contains, so that the release archives and the image carry them (the BSD, MIT and Apache
# licenses all require it of a redistributor).
#
#   scripts/third-party-licenses.sh           rewrite the file
#   scripts/third-party-licenses.sh --check   fail if it is out of date (CI)
#
# The modules are the union over every platform a release is built for (the same list as
# .goreleaser.yaml), because the platforms link different packages (macOS adds two).
# The Go standard library's license is scripts/licenses/GO-LICENSE (copied from a Go release).
# Each module contributes every license and notice file in its root, not only the main
# one: some carry extra terms for code they contain. The kind of license of each package
# comes from google/go-licenses at a pinned version, run with `go run`/`go install` and not
# added to go.mod; a module whose license is not on the allowed list (permissive licenses
# that are compatible with the AGPL-3.0) fails the run, so a new dependency cannot arrive
# without someone reading its license.
set -euo pipefail
cd "$(dirname "$0")/.."

tool="github.com/google/go-licenses/v2@v2.0.1"
allowed="Apache-2.0,BSD-2-Clause,BSD-3-Clause,ISC,MIT"
targets="linux/amd64 linux/arm64 darwin/amd64 darwin/arm64"
scratch=$(mktemp -d)
trap 'rm -rf "$scratch"' EXIT

# Build the tool for this machine first; GOOS and GOARCH below are for the analysis.
GOFLAGS=-mod=mod GOBIN="$scratch/bin" go install "$tool"
licenses="$scratch/bin/go-licenses"

for target in $targets; do
  export GOFLAGS=-mod=mod GOOS="${target%/*}" GOARCH="${target#*/}" CGO_ENABLED=0
  "$licenses" check ./cmd/hookinlet --ignore github.com/hookinlet/hookinlet \
    --allowed_licenses="$allowed" 2>"$scratch/check.err" ||
    { cat "$scratch/check.err" >&2; echo "third-party-licenses: a dependency has a license that is not on the allowed list ($allowed), for $target" >&2; exit 1; }
  "$licenses" report ./cmd/hookinlet --ignore github.com/hookinlet/hookinlet 2>/dev/null >> "$scratch/report.csv" ||
    { echo "third-party-licenses: go-licenses report failed for $target" >&2; exit 1; }
  # path, directory of every module linked in for this target
  go list -deps -f '{{with .Module}}{{if not .Main}}{{.Path}} {{.Dir}}{{end}}{{end}}' ./cmd/hookinlet >> "$scratch/modules.txt"
done
unset GOOS GOARCH CGO_ENABLED GOFLAGS

LC_ALL=C python3 - "$scratch/report.csv" "$scratch/modules.txt" "$PWD/scripts/licenses/GO-LICENSE" > "$scratch/THIRD_PARTY_LICENSES" <<'PY'
import csv, os, sys
report, modules, golicense = sys.argv[1:4]
mods = {}
for line in open(modules):
    p, d = line.split(" ", 1)
    mods[p] = d.strip()
kinds = {m: set() for m in mods}
for row in csv.reader(open(report)):
    pkg, _url, kind = row
    for m in kinds:
        if pkg == m or pkg.startswith(m + "/"):
            kinds[m].add(kind)
print("hookinlet is licensed under the GNU Affero General Public License, version 3 only")
print("(see LICENSE). The binary also contains the following third-party software, under")
print("the licenses below. This file is generated by scripts/third-party-licenses.sh.")
def section(title, kind, directory, only=None):
    print()
    print("=" * 80)
    print(title)
    if kind:
        print("License: " + kind)
    print("=" * 80)
    names = only or sorted(n for n in os.listdir(directory)
                           if n.upper().startswith(("LICENSE", "LICENCE", "NOTICE", "COPYING", "PATENTS"))
                           and os.path.isfile(os.path.join(directory, n)))
    if not names:
        sys.exit("no license file in " + directory)
    for n in names:
        print()
        print("--- " + n + " ---")
        sys.stdout.write(open(os.path.join(directory, n), encoding="utf-8", errors="replace").read())
        print()
# The Go distribution's LICENSE, kept in the repository: not every way of installing Go
# ships the file (Homebrew's does not), and the result must not depend on the machine.
section("The Go standard library and runtime (compiled into every Go program)", "BSD-3-Clause", os.path.dirname(golicense), only=[os.path.basename(golicense)])
for m in sorted(mods):
    section(m, ", ".join(sorted(kinds[m])) or "see the files below", mods[m])
PY

out="$scratch/THIRD_PARTY_LICENSES"
if [ "${1:-}" = "--check" ]; then
  if ! diff -u THIRD_PARTY_LICENSES "$out" > "$scratch/license.diff"; then
    head -40 "$scratch/license.diff" >&2
    echo "third-party-licenses: THIRD_PARTY_LICENSES is out of date; run scripts/third-party-licenses.sh and commit the result" >&2
    exit 1
  fi
  echo "ok   THIRD_PARTY_LICENSES lists the modules the release binaries are built from"
  exit 0
fi
cp "$out" THIRD_PARTY_LICENSES
echo "wrote THIRD_PARTY_LICENSES ($(grep -c '^License:' THIRD_PARTY_LICENSES) entries)"
