#!/usr/bin/env bash
# Writes THIRD_PARTY_LICENSES: the license text of every module that the hookinlet
# binary is built from, so that the release archives and the image carry them (the
# BSD, MIT and Apache licenses all require it of a redistributor).
#
#   scripts/third-party-licenses.sh           rewrite the file
#   scripts/third-party-licenses.sh --check   fail if it is out of date (CI)
#
# It uses google/go-licenses at a pinned version, run with `go run` and not added to
# go.mod. The set is the one for linux/amd64, which is what a release is built for;
# the other release targets use a subset of the same modules. A module whose license
# is not on the allowed list (permissive licenses that are compatible with the
# AGPL-3.0) fails the run, so a new dependency cannot arrive without someone reading
# its license.
set -euo pipefail
cd "$(dirname "$0")/.."

tool="github.com/google/go-licenses/v2@v2.0.1"
allowed="Apache-2.0,BSD-2-Clause,BSD-3-Clause,ISC,MIT"
scratch=$(mktemp -d)
trap 'rm -rf "$scratch"' EXIT

# Build the tool for this machine first; GOOS and GOARCH below are for the analysis.
GOFLAGS=-mod=mod GOBIN="$scratch/bin" go install "$tool"
licenses="$scratch/bin/go-licenses"
export GOFLAGS=-mod=mod GOOS=linux GOARCH=amd64 CGO_ENABLED=0

"$licenses" check ./cmd/hookinlet --ignore github.com/hookinlet/hookinlet \
  --allowed_licenses="$allowed" 2>"$scratch/check.err" ||
  { cat "$scratch/check.err" >&2; echo "third-party-licenses: a dependency has a license that is not on the allowed list ($allowed)" >&2; exit 1; }
"$licenses" report ./cmd/hookinlet --ignore github.com/hookinlet/hookinlet 2>"$scratch/report.err" | sort -u > "$scratch/report.csv" ||
  { cat "$scratch/report.err" >&2; exit 1; }
"$licenses" save ./cmd/hookinlet --ignore github.com/hookinlet/hookinlet --save_path="$scratch/lic" 2>"$scratch/save.err" ||
  { cat "$scratch/save.err" >&2; exit 1; }

out="$scratch/THIRD_PARTY_LICENSES"
{
  echo "hookinlet is licensed under the GNU Affero General Public License, version 3 only"
  echo "(see LICENSE). The binary also contains the following third-party software, under"
  echo "the licenses below. This file is generated by scripts/third-party-licenses.sh."
  while IFS=, read -r pkg url license; do
    [ -n "$pkg" ] || continue
    echo
    echo "================================================================================"
    echo "$pkg"
    echo "License: $license"
    echo "Source:  $url"
    echo "================================================================================"
    dir="$scratch/lic/$pkg"
    for f in "$dir"/LICENSE* "$dir"/NOTICE* "$dir"/COPYING*; do
      [ -f "$f" ] || continue
      echo
      echo "--- $(basename "$f") ---"
      cat "$f"
    done
  done < "$scratch/report.csv"
} > "$out"

if [ "${1:-}" = "--check" ]; then
  if ! diff -u THIRD_PARTY_LICENSES "$out" >/dev/null; then
    echo "third-party-licenses: THIRD_PARTY_LICENSES is out of date; run scripts/third-party-licenses.sh and commit the result" >&2
    exit 1
  fi
  echo "ok   THIRD_PARTY_LICENSES lists the modules the binary is built from"
  exit 0
fi
cp "$out" THIRD_PARTY_LICENSES
echo "wrote THIRD_PARTY_LICENSES ($(grep -c '^License:' THIRD_PARTY_LICENSES) modules)"
